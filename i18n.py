_EMOJI = re.compile(
    "[\U0001F000-\U0001FAFF\u2600-\u27BF\u2B00-\u2BFF\u2190-\u21FF\u23E9-\u23FF\uFE0F\u200D\u20E3]+")


def _plain(text):
    """The interface uses text only: emoji and decorative arrows are removed here, once."""
    if not isinstance(text, str):
        return text
    return re.sub(r"[ \t]{2,}", " ", _EMOJI.sub("", text)).strip()


def t_lang(key, language=None, **kwargs):
    """Translate `key` for an explicit language code (emails, chatbot, tests)."""
    lang = language or _FALLBACK_LANG
    table = TRANSLATIONS.get(lang, {})
    text = table.get(key)
    if text is None:
        text = TRANSLATIONS[_FALLBACK_LANG].get(key, key)
    if kwargs:
        try:
            return _plain(text.format(**kwargs))
        except Exception:
            return _plain(text)
    return _plain(text)


def T(key, **kwargs):
    """Translate `key` for the session's language; falls back to English."""
    language = kwargs.pop("language", None)
    if language is None:
        try:
            language = st.session_state.get("lang", _FALLBACK_LANG)
        except Exception:
            language = _FALLBACK_LANG
    return t_lang(key, language=language, **kwargs)


def TLIST(key):
    """Return a list-valued translation (weekdays, months)."""
    lang = st.session_state.get("lang", _FALLBACK_LANG)
    val = TRANSLATIONS.get(lang, {}).get(key)
    if val is None:
        val = TRANSLATIONS[_FALLBACK_LANG].get(key, [])
    return val


