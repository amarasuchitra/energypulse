def format_localized_date(date_value, language=None):
    """
    Format a date in the conventional order for the given language, e.g.
    "27 Sep 2026" for English, "27-09-2026" for Hindi, "2026-09-27" for
    Kannada and Telugu. Accepts a pd.Timestamp / datetime / date.
    """
    if date_value is None or (isinstance(date_value, float) and date_value != date_value):
        return ""
    import pandas as _pd
    try:
        dt = _pd.Timestamp(date_value)
    except (ValueError, TypeError):
        return ""
    if dt is None or dt is _pd.NaT:
        return ""
    lang = language
    if lang is None:
        try:
            lang = st.session_state.get("lang", _FALLBACK_LANG)
        except Exception:
            lang = _FALLBACK_LANG
    fmt = {
        "en": "day",
        "hi": "dmy",
        "kn": "ymd",
        "te": "ymd",
    }.get(lang, "day")
    d, m, y = dt.day, dt.month, dt.year
    if fmt == "dmy":
        return f"{d:02d}-{m:02d}-{y}"
    if fmt == "ymd":
        return f"{y}-{m:02d}-{d:02d}"
    try:
        month = dt.strftime("%b")
    except (ValueError, AttributeError):
        month = f"{m:02d}"
    return f"{d} {month} {y}"


def format_localized_month(date_value, language=None):
    """
    Format a month as "<localized month> <year>" for the given language
    (defaults to the session language, like T()). Accepts a pd.Timestamp /
    datetime / date, or an English "%B %Y" string.
    """
    if date_value is None:
        return ""
    import datetime as _dt
    import pandas as _pd
    try:
        if isinstance(date_value, str):
            try:
                dt = _dt.datetime.strptime(date_value, "%B %Y")
            except ValueError:
                dt = _pd.Timestamp(date_value).to_pydatetime()
        else:
            dt = _pd.Timestamp(date_value).to_pydatetime()
        lang = language
        if lang is None:
            try:
                lang = st.session_state.get("lang", _FALLBACK_LANG)
            except Exception:
                lang = _FALLBACK_LANG
        months_list = TRANSLATIONS.get(lang, {}).get("months")
        if not months_list:
            months_list = TRANSLATIONS[_FALLBACK_LANG].get("months", [])
        if months_list and len(months_list) >= 12:
            return f"{months_list[dt.month - 1]} {dt.year}"
        return dt.strftime("%B %Y")
    except Exception:
        return str(date_value)
